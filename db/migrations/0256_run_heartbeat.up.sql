-- 0256 run 的存活心跳。
--
-- 恢复监控判定一轮 run 是否还在被推进，改为只认它的心跳（agent_run.heartbeat_at）：由持有这轮 run 的
-- 进程续约，且只在有新的操作开始、或有未到期的在途操作时续约。此前看的是任务最近有没有新的模型调用、
-- 工具调用记录——记录在操作结束时才写，一个有超时的长操作（十几分钟的扫描）在途时是空白，会被当成
-- 停摆：run 被回收重投，同一个动作从头再跑。
--
-- 这不是 0237 删掉的那种心跳：那是任务行上另一个独立的判死方，与恢复监控抢着处置同一批任务。这里是
-- 恢复监控（唯一的判定方）的输入，判定与处置只在这一处。默认取建行时刻，开跑时由进程重置并续约。
ALTER TABLE agent_run ADD COLUMN heartbeat_at timestamptz NOT NULL DEFAULT now();
